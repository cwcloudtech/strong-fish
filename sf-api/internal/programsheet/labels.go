// heading looks a word up, falling back to English for a locale this app does
// not carry - which prints something readable rather than a blank column.
func Heading(locale, key string) string {
	if words, ok := labels[locale]; ok {
		if word, ok := words[key]; ok {
			return word
		}
	}
	return labels["en"][key]
}

func WeekLabel(locale string, number int) string {
	// Week zero is a program whose sessions were never numbered - hand-built
	// rather than imported. "Week 0" would be a lie about the block's shape.
	if number <= 0 {
		return Heading(locale, "weekless")
	}
	return fmt.Sprintf(Heading(locale, "week"), number)
}

func DayLabel(locale string, number int) string {
	if number <= 0 {
		return Heading(locale, "day")
	}
	return fmt.Sprintf(Heading(locale, "day"), number)
}

func RestLabel(locale string) string { return Heading(locale, "rest") }

// LongDate writes a date the way a credit line reads it - "19 October 2026",
// "19 octobre 2026" - from the sheet's own month names.
//
// Go's time package only knows English ones, and pulling a localization
// library in to name twelve months would be a dependency for a table.
func LongDate(locale string, at time.Time) string {
	months := strings.Split(Heading(locale, "months"), ",")
	month := int(at.Month()) - 1
	if month < 0 || month >= len(months) {
		return at.Format("2006-01-02")
	}
	if locale == "en" {
		// "19th of October 2026" reads as a date; "19 October" reads as one
		// too, and the ordinal is what the English form is asked for.
		return fmt.Sprintf("%s %s of %d", months[month], ordinal(at.Day()), at.Year())
	}
	return fmt.Sprintf("%d %s %d", at.Day(), months[month], at.Year())
}

// GeneratedBy is the credit under an AI reading.
func GeneratedBy(locale, connection string, at time.Time) string {
	return fmt.Sprintf(Heading(locale, "aiGeneratedBy"), connection, LongDate(locale, at))
}

// ordinal is 1st, 2nd, 3rd, 4th - including the three teens that look like
// they should take st, nd and rd and do not.
func ordinal(day int) string {
	suffix := "th"
	if day < 11 || day > 13 {
		switch day % 10 {
		case 1:
			suffix = "st"
		case 2:
			suffix = "nd"
		case 3:
			suffix = "rd"
		}
	}
	return fmt.Sprintf("%d%s", day, suffix)
}
